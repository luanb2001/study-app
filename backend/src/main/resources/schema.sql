CREATE TABLE IF NOT EXISTS study_entries (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36),
    study_date DATE NOT NULL,
    subject VARCHAR(120) NOT NULL,
    subject_key VARCHAR(120) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    duration_minutes INTEGER NOT NULL,
    session_count INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_study_entries_subject_date
    ON study_entries (subject_key, study_date);

CREATE TABLE IF NOT EXISTS scheduled_studies (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36),
    study_date DATE NOT NULL,
    subject VARCHAR(120) NOT NULL,
    session_count INTEGER NOT NULL,
    study_minutes INTEGER NOT NULL,
    break_minutes INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS review_schedules (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36),
    subject VARCHAR(120) NOT NULL,
    subject_key VARCHAR(200) NOT NULL,
    due_date DATE NOT NULL,
    interval_index INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS app_users (
    id VARCHAR(36) PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE app_users ADD COLUMN IF NOT EXISTS email_verified BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE study_entries ADD COLUMN IF NOT EXISTS user_id VARCHAR(36);
ALTER TABLE scheduled_studies ADD COLUMN IF NOT EXISTS user_id VARCHAR(36);
ALTER TABLE review_schedules ADD COLUMN IF NOT EXISTS user_id VARCHAR(36);
ALTER TABLE review_schedules ALTER COLUMN subject_key VARCHAR(200);
CREATE INDEX IF NOT EXISTS idx_study_entries_user_date
    ON study_entries (user_id, study_date);
CREATE INDEX IF NOT EXISTS idx_scheduled_studies_user_date
    ON scheduled_studies (user_id, study_date);
CREATE UNIQUE INDEX IF NOT EXISTS idx_review_schedules_user_subject
    ON review_schedules (user_id, subject_key);
CREATE TABLE IF NOT EXISTS applied_sync_changes (
    user_id VARCHAR(36) NOT NULL,
    change_id VARCHAR(36) NOT NULL,
    PRIMARY KEY (user_id, change_id)
);
CREATE TABLE IF NOT EXISTS sync_entity_versions (
    user_id VARCHAR(36) NOT NULL,
    entity_type VARCHAR(32) NOT NULL,
    entity_id VARCHAR(36) NOT NULL,
    version BIGINT NOT NULL,
    deleted BOOLEAN NOT NULL,
    PRIMARY KEY (user_id, entity_type, entity_id)
);
CREATE TABLE IF NOT EXISTS sync_change_log (
    change_sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    change_id VARCHAR(36) NOT NULL,
    entity_type VARCHAR(32) NOT NULL,
    entity_id VARCHAR(36) NOT NULL,
    operation VARCHAR(16) NOT NULL,
    version BIGINT NOT NULL,
    payload CLOB
);
CREATE INDEX IF NOT EXISTS idx_sync_change_log_user_sequence
    ON sync_change_log (user_id, change_sequence);
CREATE TABLE IF NOT EXISTS refresh_tokens (
    token_hash VARCHAR(64) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user
    ON refresh_tokens (user_id, revoked);
CREATE TABLE IF NOT EXISTS auth_action_tokens (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    purpose VARCHAR(32) NOT NULL,
    token_hash VARCHAR(100) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_auth_action_tokens_user_purpose
    ON auth_action_tokens (user_id, purpose, created_at);
